
import React, { useState } from 'react';
import {
  Box,
  Card,
  CardContent,
  Typography,
  TextField,
  Button,
  Chip,
  IconButton,
  Drawer,
  Divider,
  List,
  ListItem,
  ListItemText,
  CircularProgress,
  Alert,
  InputAdornment,
  Slider,
} from '@mui/material';
import {
  Search as SearchIcon,
  OpenInNew as OpenInNewIcon,
  Send as SendIcon,
  Close as CloseIcon,
  LocationOn as LocationIcon,
  Business as CompanyIcon,
  Refresh as RefreshIcon,
} from '@mui/icons-material';
import { useJobs } from '../hooks/useJobs';
import { formatSource, formatRelativeTime } from '../utils/formatters';
import type { PendingOutreachJob } from '../api/types';

export const Jobs: React.FC = () => {
  const [searchQuery, setSearchQuery] = useState('');
  const [minScore, setMinScore] = useState(50);
  const [selectedJob, setSelectedJob] = useState<PendingOutreachJob | null>(null);
  const [drawerOpen, setDrawerOpen] = useState(false);
  
  const { pendingOutreach, isPendingOutreachLoading, refetchPendingOutreach, runQuery, isRunningQuery, queryResult } = useJobs();

  const handleSearch = () => {
    runQuery({ query: searchQuery, min_score: minScore });
  };

  const handleJobClick = (job: PendingOutreachJob) => {
    setSelectedJob(job);
    setDrawerOpen(true);
  };

  const handleCloseDrawer = () => {
    setDrawerOpen(false);
    setSelectedJob(null);
  };

  const handleSendOutreach = () => {
    if (selectedJob) {
      console.log('Send outreach for job:', selectedJob.id);
    }
  };

  const jobs = pendingOutreach?.jobs || [];
  const filteredJobs = jobs.filter((job) =>
    job.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
    job.company.toLowerCase().includes(searchQuery.toLowerCase())
  );

  return (
    <Box>
      {/* Header Section */}
      <Box sx={{ mb: 4 }}>
        <Typography variant="h4" fontWeight={700} gutterBottom>
          Jobs
        </Typography>
        <Typography variant="body1" color="text.secondary">
          Manage and track your job applications
        </Typography>
      </Box>

      {/* Search & Filter Section */}
      <Card sx={{ mb: 3 }}>
        <CardContent>
          <Box sx={{ display: 'flex', gap: 2, flexWrap: 'wrap', alignItems: 'center' }}>
            <TextField
              placeholder="Search jobs..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              size="small"
              sx={{ flex: 1, minWidth: 200 }}
              InputProps={{
                startAdornment: (
                  <InputAdornment position="start">
                    <SearchIcon color="action" />
                  </InputAdornment>
                ),
              }}
            />
            
            <Box sx={{ width: 200, px: 2 }}>
              <Typography variant="body2" color="text.secondary" gutterBottom>
                Min Score: {minScore}%
              </Typography>
              <Slider
                value={minScore}
                onChange={(_, value) => setMinScore(value as number)}
                min={0}
                max={100}
                step={5}
                valueLabelDisplay="auto"
                color="primary"
              />
            </Box>

            <Button
              variant="contained"
              onClick={handleSearch}
              disabled={isRunningQuery || !searchQuery.trim()}
              startIcon={isRunningQuery ? <CircularProgress size={20} color="inherit" /> : <RefreshIcon />}
            >
              {isRunningQuery ? 'Searching...' : 'Fetch Jobs'}
            </Button>

            <Button
              variant="outlined"
              onClick={() => refetchPendingOutreach()}
              disabled={isPendingOutreachLoading}
            >
              Refresh
            </Button>
          </Box>

          {queryResult && (
            <Alert severity="success" sx={{ mt: 2 }}>
              {queryResult.jobs_fetched} jobs fetched using resume: {queryResult.resume_used}
            </Alert>
          )}
        </CardContent>
      </Card>

      {/* Jobs List */}
      <Typography variant="h6" fontWeight={600} sx={{ mb: 2 }}>
        {filteredJobs.length} Jobs Found
      </Typography>

      {isPendingOutreachLoading ? (
        <Box sx={{ display: 'flex', justifyContent: 'center', py: 4 }}>
          <CircularProgress />
        </Box>
      ) : filteredJobs.length === 0 ? (
        <Card>
          <CardContent sx={{ textAlign: 'center', py: 6 }}>
            <Typography variant="h6" color="text.secondary" gutterBottom>
              No jobs found
            </Typography>
            <Typography variant="body2" color="text.secondary">
              Try searching for jobs or adjusting your filters
            </Typography>
          </CardContent>
        </Card>
      ) : (
        <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
          {filteredJobs.map((job: PendingOutreachJob) => (
            <Card
              key={job.id}
              sx={{
                cursor: 'pointer',
                transition: 'transform 0.2s, box-shadow 0.2s',
                '&:hover': {
                  transform: 'translateY(-2px)',
                  boxShadow: 3,
                },
              }}
              onClick={() => handleJobClick(job)}
            >
              <CardContent>
                <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
                  <Box sx={{ flex: 1 }}>
                    <Typography variant="h6" fontWeight={600}>
                      {job.title}
                    </Typography>
                    <Box sx={{ display: 'flex', gap: 1, alignItems: 'center', mt: 1, flexWrap: 'wrap' }}>
                      <Chip
                        icon={<CompanyIcon />}
                        label={job.company}
                        size="small"
                        variant="outlined"
                      />
                      <Chip
                        icon={<LocationIcon />}
                        label={job.location || 'Remote'}
                        size="small"
                        variant="outlined"
                      />
                      <Chip
                        label={formatSource(job.source)}
                        size="small"
                        color="primary"
                        variant="outlined"
                      />
                    </Box>
                  </Box>
                  <Box sx={{ display: 'flex', gap: 1 }}>
                    {job.url && (
                      <IconButton
                        size="small"
                        onClick={(e) => {
                          e.stopPropagation();
                          window.open(job.url, '_blank');
                        }}
                      >
                        <OpenInNewIcon fontSize="small" />
                      </IconButton>
                    )}
                    <IconButton
                      size="small"
                      color="primary"
                      onClick={(e) => {
                        e.stopPropagation();
                        handleJobClick(job);
                      }}
                    >
                      <SendIcon fontSize="small" />
                    </IconButton>
                  </Box>
                </Box>
              </CardContent>
            </Card>
          ))}
        </Box>
      )}

      {/* Job Details Drawer */}
      <Drawer
        anchor="right"
        open={drawerOpen}
        onClose={handleCloseDrawer}
        PaperProps={{ sx: { width: { xs: '100%', sm: 450 } } }}
      >
        {selectedJob && (
          <Box sx={{ p: 3 }}>
            <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', mb: 2 }}>
              <Typography variant="h6" fontWeight={600}>
                Job Details
              </Typography>
              <IconButton onClick={handleCloseDrawer}>
                <CloseIcon />
              </IconButton>
            </Box>

            <Divider sx={{ mb: 3 }} />

            <Typography variant="h6" fontWeight={600} gutterBottom>
              {selectedJob.title}
            </Typography>

            <Box sx={{ display: 'flex', gap: 1, mb: 3, flexWrap: 'wrap' }}>
              <Chip icon={<CompanyIcon />} label={selectedJob.company} size="small" />
              <Chip icon={<LocationIcon />} label={selectedJob.location || 'Remote'} size="small" />
            </Box>

            <List dense>
              <ListItem>
                <ListItemText
                  primary="Source"
                  secondary={formatSource(selectedJob.source)}
                />
              </ListItem>
            </List>

            {selectedJob.url && (
              <Box sx={{ mt: 3 }}>
                <Button
                  variant="contained"
                  fullWidth
                  startIcon={<OpenInNewIcon />}
                  onClick={() => window.open(selectedJob.url, '_blank')}
                  sx={{ mb: 2 }}
                >
                  View Original Listing
                </Button>
              </Box>
            )}

            <Button
              variant="outlined"
              color="primary"
              fullWidth
              startIcon={<SendIcon />}
              onClick={handleSendOutreach}
            >
              Send Outreach
            </Button>
          </Box>
        )}
      </Drawer>
    </Box>
  );
};

export default Jobs;

